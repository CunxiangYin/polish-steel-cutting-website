// 翻译函数
function translate(key, language = 'en') {
    const langData = TRANSLATIONS[language] || TRANSLATIONS['en'];
    return langData[key] || TRANSLATIONS['en'][key] || key;
}

// 应用翻译到页面
function applyTranslations(language) {
    // 翻译所有带有 data-i18n 属性的元素
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.dataset.i18n;
        const translation = translate(key, language);
        
        if (element.tagName === 'INPUT' || element.tagName === 'TEXTAREA') {
            element.placeholder = translation;
        } else {
            element.textContent = translation;
        }
    });
    
    // 翻译所有带有 data-i18n-title 属性的元素（用于 title 属性）
    document.querySelectorAll('[data-i18n-title]').forEach(element => {
        const key = element.dataset.i18nTitle;
        element.title = translate(key, language);
    });
    
    // 更新页面标题
    if (TRANSLATIONS[language] && TRANSLATIONS[language]['page.title']) {
        document.title = TRANSLATIONS[language]['page.title'];
    }
}

// 导出翻译系统
window.TRANSLATIONS = TRANSLATIONS;
window.translate = translate;
window.applyTranslations = applyTranslations;